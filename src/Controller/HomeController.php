<?php

namespace App\Controller;

use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class HomeController extends AbstractController
{
    #[Route('/', name: 'home')]
    public function __invoke(): Response
    {
        $generatedAt = (new \DateTimeImmutable())->format('H:i:s.v');

        $response = new Response(<<<HTML
            <!doctype html>
            <html lang="en">
            <head><meta charset="utf-8"><title>invalidate-less</title></head>
            <body>
                <h1>invalidate-less</h1>
                <p>Page generated by Symfony at <strong>{$generatedAt}</strong>.</p>
                <p>Reload through Varnish: if this time doesn't change, the page came from the cache.</p>
            </body>
            </html>
            HTML);

        // Browsers must not cache the page; shared caches (Varnish, CloudFront) may keep it for 60 seconds.
        $response->setPublic();
        $response->setMaxAge(0);
        $response->setSharedMaxAge(60);

        return $response;
    }
}
